#!/usr/bin/env python3
"""Human-authored (non-generated) transfer and false-positive evaluation.

Both reviewers observe that a corpus generated by a second LLM pipeline cannot
demonstrate generalization to real attacks, and that its source provenance is
not verifiable. This script therefore evaluates the same trained detectors on
two corpora whose provenance *is* verifiable because no language model is
involved in producing them:

* an aggregated public corpus of real phishing and real legitimate email;
* the Apache SpamAssassin public corpus (real legitimate mail and real spam),
  used as an all-negative false-positive stress test.

Neither corpus is used for training, feature selection, calibration, or
threshold selection.
"""

from __future__ import annotations

import time

import numpy as np
import pandas as pd

from rev_common import (
    RESULTS,
    SEEDS,
    base,
    encode_minilm,
    load_corpora,
    load_embeddings,
    split_frames,
)
from rev_realworld_data import realworld_conditions


def main() -> None:
    started = time.time()
    primary, external, binary, spam = load_corpora()
    primary_embeddings, _ = load_embeddings(primary, external)
    conditions = realworld_conditions()

    embeddings = {}
    for name, frame in conditions.items():
        print(f"embedding {name} ({len(frame)} rows) ...", flush=True)
        embeddings[name] = encode_minilm(frame["text"])

    blocks: list[pd.DataFrame] = []
    for seed in SEEDS:
        frames = split_frames(binary, external, spam, seed)
        train_all = frames["train_all"]
        train_clean = frames["train_clean"]
        models = {
            "Word LR, clean-only": base.WordModel.fit(
                train_clean["text"].tolist(), train_clean["label"].to_numpy()
            ),
            "Word LR, linked-augmented": base.WordModel.fit(
                train_all["text"].tolist(), train_all["label"].to_numpy()
            ),
            "Char+word LR, linked-augmented": base.CharWordModel.fit(
                train_all["text"].tolist(), train_all["label"].to_numpy()
            ),
            "MiniLM LR, clean-only": base.EmbeddingModel.fit(
                primary_embeddings[train_clean.index.to_numpy()],
                train_clean["label"].to_numpy(),
            ),
            "MiniLM LR, linked-augmented": base.EmbeddingModel.fit(
                primary_embeddings[train_all.index.to_numpy()],
                train_all["label"].to_numpy(),
            ),
        }
        for name, frame in conditions.items():
            block = pd.DataFrame(
                {
                    "seed": seed,
                    "condition": name,
                    "row_index": np.arange(len(frame)),
                    "group_id": frame["group_id"].to_numpy(),
                    "label": frame["label"].to_numpy().astype(int),
                }
            )
            for model_name, model in models.items():
                if isinstance(model, base.EmbeddingModel):
                    probability = model.predict_proba(embeddings[name])
                else:
                    probability = model.predict_proba(frame["text"].tolist())
                block[f"probability_{base.model_slug(model_name)}"] = probability
            blocks.append(block)
        print(f"seed {seed} complete", flush=True)

    table = pd.concat(blocks, ignore_index=True)
    table.to_csv(RESULTS / "revision_realworld_probabilities.csv", index=False)

    columns = [c for c in table.columns if c.startswith("probability_")]
    rows = []
    for (condition, seed), block in table.groupby(["condition", "seed"]):
        y = block["label"].to_numpy()
        for column in columns:
            probability = block[column].to_numpy()
            if y.max() == 0:
                rows.append(
                    {
                        "condition": condition,
                        "seed": seed,
                        "model": column.replace("probability_", ""),
                        "n": len(y),
                        "fpr_at_0_5": float((probability >= 0.5).mean()),
                    }
                )
            else:
                result = base.metrics(y, probability)
                result["fpr_at_0_5"] = float((probability[y == 0] >= 0.5).mean())
                rows.append(
                    {
                        "condition": condition,
                        "seed": seed,
                        "model": column.replace("probability_", ""),
                        "n": len(y),
                        **result,
                    }
                )
    detail = pd.DataFrame(rows)
    detail.to_csv(RESULTS / "revision_realworld_metrics_by_seed.csv", index=False)
    numeric = [c for c in detail.columns if c not in {"condition", "seed", "model"}]
    summary = (
        detail.groupby(["condition", "model"], as_index=False)[numeric]
        .agg(["mean", "std"])
        .reset_index()
    )
    summary.columns = [
        "_".join(part for part in column if part).rstrip("_")
        if isinstance(column, tuple)
        else column
        for column in summary.columns
    ]
    summary = summary.drop(columns=["index"], errors="ignore")
    summary.to_csv(RESULTS / "revision_realworld_summary.csv", index=False)
    print(
        summary[
            [c for c in summary.columns if c in
             ("condition", "model", "f1_mean", "precision_mean", "recall_mean",
              "pr_auc_mean", "ece_mean", "fpr_at_0_5_mean")]
        ].to_string(index=False)
    )
    print(f"done in {time.time() - started:.0f}s")


if __name__ == "__main__":
    main()
